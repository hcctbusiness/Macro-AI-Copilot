"""Run the full Macro-AI-Copilot pipeline and write docs/*.png and docs/results.md.

    python run_macro_ai_copilot.py            # uses cached data if present
    python run_macro_ai_copilot.py --refresh  # re-download FRED + Yahoo data
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402
import quantcore as qc  # noqa: E402

from macro_ai_copilot import config, pipeline  # noqa: E402

ROWS = ["CAGR", "Ann. Vol", "Sharpe", "Sortino", "Max Drawdown", "Calmar", "Beta vs EW",
        "Avg Daily Turnover", "Annual Cost Drag"]


def pct_table(df: pd.DataFrame, fmt: str = "{:+.1f}%") -> str:
    head = "| | " + " | ".join(df.columns) + " |"
    sep = "|---|" + "---:|" * df.shape[1]
    rows = ["| " + str(i) + " | " + " | ".join(fmt.format(v * 100) for v in r) + " |" for i, r in df.iterrows()]
    return "\n".join([head, sep, *rows])


def write_report(out: pipeline.PipelineOutput, path: Path) -> str:
    e = out.extra
    L = e["latest"]
    stats_md = qc.report.to_markdown(out.stats.loc[[r for r in ROWS if r in out.stats.index]])
    d = out.diagnostics
    diag_md = "\n".join([
        "| Metric | Logistic | Gradient boosting |", "|---|---:|---:|",
        f"| OOS months | {int(d.loc['Months','logit'])} | {int(d.loc['Months','gbm'])} |",
        f"| Hit rate (beats basket?) | {d.loc['Hit rate','logit']:.1%} | {d.loc['Hit rate','gbm']:.1%} |",
        f"| Mean rank IC | {d.loc['Mean rank IC','logit']:.3f} | {d.loc['Mean rank IC','gbm']:.3f} |",
        f"| IC t-stat | {d.loc['IC t-stat','logit']:.2f} | {d.loc['IC t-stat','gbm']:.2f} |",
        f"| Top-minus-bottom asset, avg monthly | {d.loc['Top-minus-bottom (monthly)','logit']:.2%} | "
        f"{d.loc['Top-minus-bottom (monthly)','gbm']:.2%} |",
    ])
    w = L["weights"]
    w_md = "| " + " | ".join(w.index) + " |\n|" + "---:|" * len(w) + "\n| " + " | ".join(f"{x:.0%}" for x in w.values) + " |"
    s = e["sentiment"]
    cm = s["confusion"]
    cm_md = "| label \\ predicted | " + " | ".join(cm.columns) + " |\n|---|" + "---:|" * len(cm.columns) + "\n" + \
        "\n".join(f"| {i} | " + " | ".join(str(v) for v in r) + " |" for i, r in cm.iterrows())
    share = ", ".join(f"{k} {v:.0%}" for k, v in e["quad_share"].items())
    gshare = ", ".join(f"{k} {v:.0%}" for k, v in e["gmm_share"].items())
    txt = f"""# Macro-AI-Copilot — results

Generated by `python run_macro_ai_copilot.py`. Out-of-sample backtest period
**{e['start']:%Y-%m-%d} → {e['end']:%Y-%m-%d}** (daily returns, monthly rebalancing, trades executed the
day after the month-end signal, {config.COMMISSION_BPS:g} bp commission + {config.SLIPPAGE_BPS:g} bp slippage on turnover).
Universe: {', '.join(config.ASSETS)}. Long-only, max {config.MAX_WEIGHT:.0%} per asset for the ML tilt.

## Strategy performance

{stats_md}

![Tearsheet](tearsheet.png)

## Out-of-sample prediction quality

Each month the models predict, for every ETF, the probability that it beats the equal-weight
basket over the next month. Models are retrained on an expanding window using only labels already
realised (logistic monthly, GBM every 3 months).

{diag_md}

### Robustness: publication lag

Re-running the logistic model with every monthly macro series lagged **2 months** instead of 1
(a stricter point-in-time assumption) gives:

{qc.report.to_markdown(e['robustness'].loc[["CAGR", "Ann. Vol", "Sharpe", "Max Drawdown"]])}

Mean rank IC with a 2-month lag: {d.loc['Mean rank IC','logit_lag2']:.3f} (t = {d.loc['IC t-stat','logit_lag2']:.2f}).

## Regimes

Share of out-of-sample months by quadrant: {share}.
Share by GMM regime: {gshare}.

Annualised average next-month return per asset, grouped by the regime known at the decision date
(descriptive, full available history since 2006 — not a trading result):

**Quadrant**

{pct_table(out.perf_quad)}

**GMM regime**

{pct_table(out.perf_gmm)}

![Regimes](regimes.png)

## Latest reading (data through {e['end']:%Y-%m-%d})

- Quadrant: **{L['quadrant']}**; GMM regime: **{L['gmm']}**.
- ML tilt target weights:

{w_md}

## News sentiment demo (toy data, not in the backtest)

Lexicon scorer on `data/raw/news_headlines.csv` ({s['n']} hand-written demo headlines).
Accuracy vs hand labels: **{s['accuracy']:.0%}**. The lexicon and the sample were written together, so this is
an in-sample sanity check, not an out-of-sample accuracy estimate.

{cm_md}
"""
    path.write_text(txt)
    return txt


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--refresh", action="store_true", help="re-download data")
    ap.add_argument("--docs", default=str(ROOT / "docs"))
    args = ap.parse_args()
    out = pipeline.run(docs=args.docs, news_csv=ROOT / "data/raw/news_headlines.csv", refresh=args.refresh)
    write_report(out, Path(args.docs) / "results.md")
    print()
    print(out.stats.loc[[r for r in ROWS if r in out.stats.index]].round(4).to_string())
    print()
    print(out.diagnostics.round(4).to_string())
    print(f"\nWrote {args.docs}/tearsheet.png, regimes.png, results.md")


if __name__ == "__main__":
    main()
